// Tell Workbox to immediately take control of the page
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

// Take control of uncontrolled clients
clientsClaim();

// Optional: clean up old caches
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((cacheName) => {
          if (cacheName !== 'workbox-precache-v2') { // or your current cache name
            return caches.delete(cacheName);
          }
        })
      );
    })
  );
  self.clients.claim();
});

// Precache the assets generated by Vite
precacheAndRoute(self.__WB_MANIFEST || []);

// Listen for Push Events from the server
self.addEventListener('push', (event) => {
  let pushData = { title: 'Notificacão do FinVision Pro', body: 'Você tem novas atualizações!', url: '/' };
  
  if (event.data) {
    try {
      pushData = event.data.json();
    } catch (e) {
      pushData.body = event.data.text();
    }
  }

  const options = {
    body: pushData.body,
    icon: pushData.icon || '/logo.png', // Ensure you have a logo.png in public/
    badge: '/favicon.ico',
    data: {
      url: pushData.url || '/'
    },
    vibrate: [200, 100, 200, 100, 200, 100, 200]
  };

  event.waitUntil(
    self.registration.showNotification(pushData.title, options)
  );
});

// Handle click on the notification
self.addEventListener('notificationclick', (event) => {
  event.notification.close();

  const urlToOpen = event.notification.data.url || '/';

  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
      // Check if there is already a window/tab open with the target URL
      for (let i = 0; i < windowClients.length; i++) {
        const client = windowClients[i];
        if (client.url.includes(urlToOpen) && 'focus' in client) {
          return client.focus();
        }
      }
      // If no window is open, open a new one
      if (self.clients.openWindow) {
        return self.clients.openWindow(urlToOpen);
      }
    })
  );
});
